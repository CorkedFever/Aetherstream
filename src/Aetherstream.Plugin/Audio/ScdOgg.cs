namespace Aetherstream.Plugin.Audio;

/// <summary>
/// Pulls the Ogg Vorbis stream out of one of the game's SCD sound files, the format its music is
/// stored in. The stream sits after a small header and a seek table, lightly scrambled with an
/// XOR that depends on the file; undone, it is an ordinary .ogg that libvlc plays. The layout
/// and the table are as the community tools read them.
/// </summary>
internal static class ScdOgg
{
