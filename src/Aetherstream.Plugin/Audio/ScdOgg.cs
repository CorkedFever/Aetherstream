    /// <summary>The same, from an array; the harness calls this, since it cannot pass a span.</summary>
    public static byte[]? Extract(byte[] file) => Extract(file.AsSpan());

    /// <summary>The first audio entry's Ogg stream, or null when the file is not an Ogg SCD.</summary>
    public static byte[]? Extract(ReadOnlySpan<byte> file)
    {
        if (file.Length < HeaderSize + 0x20 || file[0] != (byte)'S' || file[1] != (byte)'E' || file[2] != (byte)'D' || file[3] != (byte)'B')
            return null;

        var audioCount = BitConverter.ToUInt16(file[(HeaderSize + 4)..]);
        if (audioCount == 0)
            return null;

        var audioTable = (int)BitConverter.ToUInt32(file[(HeaderSize + 0x0C)..]);
        var entry = (int)BitConverter.ToUInt32(file[audioTable..]);
        if (entry <= 0 || entry + 32 > file.Length)
            return null;

        var size = (int)BitConverter.ToUInt32(file[entry..]);
        var format = BitConverter.ToInt32(file[(entry + 12)..]);
        var subInfoSize = (int)BitConverter.ToUInt32(file[(entry + 24)..]);
        var flags = BitConverter.ToUInt32(file[(entry + 28)..]);
        if (format != 6 || size <= 0)
            return null;

        // Past the marker chunk when there is one, to the Ogg seek table header.
        var sub = entry + 32;
        if ((flags & 1) != 0)
            sub += (int)BitConverter.ToUInt32(file[(sub + 4)..]);

        var version = file[sub];
        var xorByte = file[sub + 2];
        var oggHeaderSize = (int)BitConverter.ToUInt32(file[(sub + 20)..]);
        var dataStart = entry + 32 + subInfoSize;
        var headerStart = dataStart - oggHeaderSize;
        if (headerStart < 0 || dataStart + size > file.Length)
            return null;

        var ogg = new byte[oggHeaderSize + size];
        file.Slice(headerStart, oggHeaderSize + size).CopyTo(ogg);

        switch (version)
        {
            case 2:
                for (var i = 0; i < oggHeaderSize; i++)
                    ogg[i] ^= xorByte;
                break;
            case 3:
                var byte1 = (byte)(size & 0x7F);
                var byte2 = (byte)(byte1 & 0x3F);
                for (var i = 0; i < ogg.Length; i++)
                    ogg[i] = (byte)(XorTable[(byte2 + i) & 0xFF] ^ ogg[i] ^ byte1);
                break;
        }

        return ogg;
    }
}
